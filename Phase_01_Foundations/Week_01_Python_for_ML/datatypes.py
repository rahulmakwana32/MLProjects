 
# Integer (int): Represents whole numbers
count = 10

# String (str): Represents text; can be defined using single, double, or triple quotes
user_name = "Rahul"

# Float (float): Represents numbers with a decimal point
price = 3.99

# Boolean (bool): Represents logical truth values (True or False)
is_active = True

# Displaying the data types of the variables using the type() function
data_points = [count, user_name, price, is_active]
for item in data_points:
    print(f"Value: {item} | Type: {type(item)}")
